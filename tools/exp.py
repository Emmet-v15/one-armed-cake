#!/usr/bin/env python3
"""Controlled latency-under-load experiments for a CAKE shaper.

Every trial runs a 50 Hz game-style UDP probe (64-byte payload, sequence-
numbered) against a UDP echo reflector, and:

    idle   for 2 s
    load   N bulk TCP streams for 8 s
             upload:   to tools/labsrv.py on the reflector host
             download: curl processes fetching a public test file
    tail   2 s idle

Latency and loss are reported per window: idle, start (first 1.5 s of load)
and steady (the rest of the load). Conditions are interleaved inside each
repetition, so slow drift in line capacity lands on every condition equally.
Results are appended to a JSON-lines file, one trial per line.

The router is driven over ssh to switch marking and caps between conditions.

Environment:
    REFLECTOR       host running echo/echo-server.py and tools/labsrv.py (required)
    REFLECTOR_SSH   ssh destination for that host (default: $REFLECTOR)
    ROUTER_SSH      ssh destination for the router (default: router)
    DL_URL          large file for download load (default: tele2 100 MB)

Usage:
    python exp.py upload   [--reps 5]   marking off/on x 4/16 upload streams
    python exp.py download [--reps 3]   download cap sweep, 4 streams

Load-generator pitfall: on the Windows test PC used for the paper, sockets
owned by python.exe received at ~0.45 Mbps while curl and Bun reached the full
line (same URL, back to back). Download load is therefore generated by curl.
Validate your load generator against an independent client before trusting it.
"""
import argparse
import json
import os
import socket
import statistics
import subprocess
import threading
import time

REFLECTOR = os.environ.get("REFLECTOR", "")
REFLECTOR_SSH = os.environ.get("REFLECTOR_SSH", REFLECTOR)
ROUTER_SSH = os.environ.get("ROUTER_SSH", "router")
DL_URL = os.environ.get("DL_URL", "http://speedtest.tele2.net/100MB.zip")
PORT, T_START, LOAD, TAIL, HZ, START_WIN = 5201, 2.0, 8.0, 2.0, 50, 1.5


def ssh(dest: str, cmd: str, capture: bool = True) -> str:
    r = subprocess.run(["ssh", "-n", dest, cmd], capture_output=capture, text=True, stdin=subprocess.DEVNULL)
    return (r.stdout or "").strip()


def set_marking(on: bool) -> None:
    # Off = empty router-shaper's marking chain; on = let router-shaper rewrite it.
    # (The paper's data predates the move to `table ip one_armed_cake`, when the
    # rules lived in `table ip mangle chain forward` and marked small UDP EF.)
    ssh(ROUTER_SSH, "sudo /usr/local/sbin/router-shaper mark" if on
        else "sudo nft flush chain ip one_armed_cake dscp_mark")


def set_down(cap: str, rtt: str) -> None:
    rate = "unlimited" if cap == "unlimited" else f"bandwidth {cap}kbit"
    ssh(ROUTER_SSH, f"sudo tc qdisc change dev ifb-down root cake {rate} rtt {rtt}")


def pct(v: list, p: float) -> float:
    return v[min(len(v) - 1, int(len(v) * p))]


def trial(ip: str, direction: str, streams: int) -> dict:
    total = T_START + LOAD + TAIL
    udp = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    udp.settimeout(0.2)
    sent: dict = {}
    rtt: dict = {}
    t0 = time.time() + 0.3

    def rx() -> None:
        while time.time() < t0 + total + 1.5:
            try:
                d, _ = udp.recvfrom(128)
            except OSError:
                continue
            q = int(d[:8])
            rtt[q] = (time.perf_counter() - sent[q][1]) * 1000

    def tx() -> None:
        q = 0
        while time.time() < t0 + total:
            sent[q] = (time.time() - t0, time.perf_counter())
            udp.sendto(b"%08d" % q + b"x" * 56, (ip, PORT))
            q += 1
            time.sleep(max(0, t0 + q / HZ - time.time()))

    stop = t0 + T_START + LOAD

    def upload() -> None:
        try:
            c = socket.create_connection((ip, PORT), timeout=5)
            c.sendall(b"U")
            blob = os.urandom(1 << 16)
            while time.time() < stop:
                c.send(blob)
            c.close()
        except OSError:
            pass

    probes = [threading.Thread(target=rx), threading.Thread(target=tx)]
    for t in probes:
        t.start()
    time.sleep(max(0, t0 + T_START - time.time()))
    curls, ups = [], []
    if direction == "down":
        curls = [subprocess.Popen(["curl", "-s", "-o", os.devnull, "-m", str(LOAD), "-w", "%{size_download}", DL_URL],
                                  stdout=subprocess.PIPE, stdin=subprocess.DEVNULL, text=True)
                 for _ in range(streams)]
    else:
        ups = [threading.Thread(target=upload) for _ in range(streams)]
    for t in ups:
        t.start()
    for t in ups:
        t.join()
    got = sum(int(float(c.communicate()[0] or 0)) for c in curls)
    for t in probes:
        t.join()

    res: dict = {"direction": direction, "streams": streams}
    for name, lo, hi in (("idle", 0, T_START), ("start", T_START, T_START + START_WIN),
                         ("steady", T_START + START_WIN, T_START + LOAD)):
        rows = [(t, rtt.get(q)) for q, (t, _) in sent.items() if lo <= t < hi]
        ok = sorted(v for _, v in rows if v is not None)
        res[name] = {"n": len(rows), "lost": sum(1 for _, v in rows if v is None),
                     "med": statistics.median(ok) if ok else None,
                     "p95": pct(ok, .95) if ok else None, "p99": pct(ok, .99) if ok else None,
                     "max": ok[-1] if ok else None}
    if direction == "down":
        res["goodput_mbps"] = got * 8 / LOAD / 1e6   # whole load period, ramp included
    return res


def run(conds: list, reps: int, out: str) -> None:
    ip = socket.gethostbyname(REFLECTOR)
    # anchored pattern: an unanchored `pkill -f labsrv.py` also matches the
    # shell that is launching the server, and kills it
    ssh(REFLECTOR_SSH, "pkill -f '^python3 /tmp/labsrv.py' || true")
    srv = subprocess.Popen(["ssh", "-n", REFLECTOR_SSH, "exec python3 /tmp/labsrv.py --seconds 3500"],
                           stdin=subprocess.DEVNULL)
    time.sleep(3)
    try:
        with open(out, "a") as f:
            for r in range(reps):
                for c in conds:
                    c["setup"]()
                    time.sleep(1.5)
                    res = trial(ip, c["direction"], c["streams"])
                    res.update({"cond": c["name"], "rep": r, "ts": time.time()})
                    f.write(json.dumps(res) + "\n")
                    f.flush()
                    s, st = res["start"], res["steady"]
                    print(f"rep {r} {c['name']:<26} idle {res['idle']['med'] or 0:5.1f} | start med {s['med'] or 0:6.1f} "
                          f"p99 {s['p99'] or 0:6.1f} lost {s['lost']:2d} | steady med {st['med'] or 0:6.1f} "
                          f"p99 {st['p99'] or 0:6.1f} lost {st['lost']:2d} | {res.get('goodput_mbps', 0):4.2f} Mbps",
                          flush=True)
    finally:
        ssh(REFLECTOR_SSH, "pkill -f '^python3 /tmp/labsrv.py' || true")
        srv.terminate()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("experiment", choices=["upload", "download"])
    ap.add_argument("--reps", type=int, default=None)
    ap.add_argument("--out", default=None, help="JSON-lines output (default: results-<experiment>.jsonl)")
    a = ap.parse_args()
    if not REFLECTOR:
        ap.error("set REFLECTOR to the host running echo-server.py and labsrv.py")
    if a.experiment == "upload":
        conds = [{"name": f"up{n}-{'ef' if m else 'none'}", "direction": "up", "streams": n,
                  "setup": (lambda m=m: set_marking(m))} for n in (4, 16) for m in (False, True)]
    else:
        caps = [("unlimited", "100ms"), ("5300", "30ms"), ("5100", "30ms"), ("4800", "30ms"), ("4500", "30ms")]
        conds = [{"name": f"down-{cap}-rtt{rtt}-ef", "direction": "down", "streams": 4,
                  "setup": (lambda cap=cap, rtt=rtt: (set_marking(True), set_down(cap, rtt)))} for cap, rtt in caps]
        conds.append({"name": "down-4500-rtt30ms-none", "direction": "down", "streams": 4,
                      "setup": lambda: (set_marking(False), set_down("4500", "30ms"))})
    try:
        run(conds, a.reps or (5 if a.experiment == "upload" else 3), a.out or f"results-{a.experiment}.jsonl")
    finally:
        set_marking(True)
        # put the router back on its configured profile
        ssh(ROUTER_SSH, "sudo /usr/local/sbin/router-shaper profile $(sed -n 's/^PROFILE=//p' /etc/router-shaper.conf)")


if __name__ == "__main__":
    main()
